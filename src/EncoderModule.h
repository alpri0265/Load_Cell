#pragma once
#include <Arduino.h>

// Обробка обертання енкодера EC11 (переривання S1/S2) та кнопки KEY (дебаунс/довге утримання).
namespace EncoderModule {
  void begin();
  void update();          // викликати щоітерації loop() — обробляє кнопку (час-залежна логіка)

  int8_t readStep();      // повертає -1 / 0 / +1 за одну позицію (детент) енкодера, споживає результат
  bool wasClicked();      // короткий клік, споживається один раз
  bool wasLongPressed();  // довге утримання, споживається один раз
  bool isPressed();       // поточний стан кнопки
}
